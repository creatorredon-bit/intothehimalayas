/**
 * Generates supabase/seed.sql from the typed sample dataset.
 *
 * Using the same source as the browser's offline dataset guarantees that a
 * seeded Supabase project and demo mode show identical content. Run with:
 *   node scripts/generate-seed.mjs
 */
import { build } from 'esbuild';
import path from 'node:path';
import { writeFile } from 'node:fs/promises';

const root = process.cwd();

const bundled = await build({
  entryPoints: [path.join(root, 'src/data/sample.ts')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  alias: { '@': path.join(root, 'src') },
  logLevel: 'silent',
});

const code = bundled.outputFiles[0].text;
const moduleUrl = `data:text/javascript;base64,${Buffer.from(code, 'utf8').toString('base64')}`;
const sample = await import(moduleUrl);

const { sampleDestinations, sampleTrails, sampleGuides, sampleStays } = sample;

const q = (value) => {
  if (value === null || value === undefined) return 'null';
  return `'${String(value).replace(/'/g, "''")}'`;
};
const n = (value) => (value === null || value === undefined ? 'null' : Number(value));
const b = (value) => (value ? 'true' : 'false');
const arr = (values) =>
  Array.isArray(values) && values.length > 0
    ? `array[${values.map((value) => q(value)).join(', ')}]::text[]`
    : `'{}'::text[]`;
const json = (value) => (value === null || value === undefined ? 'null' : `${q(JSON.stringify(value))}::jsonb`);

const lines = [];
lines.push('-- ---------------------------------------------------------------------------');
lines.push('-- IntotheHimalayas — seed data');
lines.push('-- Generated by scripts/generate-seed.mjs from src/data/sample.ts.');
lines.push('-- This is SAMPLE content: verify every route and listing before production use.');
lines.push('-- Apply after 0001_schema.sql, 0002_policies.sql and 0003_functions.sql.');
lines.push('-- ---------------------------------------------------------------------------');
lines.push('');
lines.push('begin;');
lines.push('');
lines.push('-- Remove previously seeded rows so the script is idempotent.');
lines.push("delete from public.trails where id::text like 'a0000000-%';");
lines.push("delete from public.destinations where id::text like 'd0000000-%';");
lines.push("delete from public.guides where id::text like 'b0000000-%';");
lines.push("delete from public.stays where id::text like 'c0000000-%';");
lines.push('');

lines.push('insert into public.destinations (id, slug, name, region, tagline, description, hero_image, best_seasons, lat, lng, featured, published) values');
lines.push(
  sampleDestinations
    .map(
      (destination) =>
        `  (${q(destination.id)}, ${q(destination.slug)}, ${q(destination.name)}, ${q(destination.region)}, ${q(
          destination.tagline,
        )}, ${q(destination.description)}, ${q(destination.heroImage)}, ${arr(destination.bestSeasons)}, ${n(
          destination.lat,
        )}, ${n(destination.lng)}, ${b(destination.featured)}, ${b(destination.published)})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
);
lines.push('');

lines.push(
  'insert into public.trails (id, slug, name, summary, description, region, destination_id, difficulty, activity, distance_km, duration_days, max_elevation_m, elevation_gain_m, start_point_name, start_lat, start_lng, best_seasons, hero_image, gallery, route_geojson, itinerary, facilities, safety_notes, permit_info, permits_required, is_sample, featured, published) values',
);
lines.push(
  sampleTrails
    .map(
      (trail) =>
        `  (${q(trail.id)}, ${q(trail.slug)}, ${q(trail.name)}, ${q(trail.summary)}, ${q(trail.description)}, ${q(
          trail.region,
        )}, ${q(trail.destinationId)}, ${q(trail.difficulty)}, ${q(trail.activity)}, ${n(trail.distanceKm)}, ${n(
          trail.durationDays,
        )}, ${n(trail.maxElevationM)}, ${n(trail.elevationGainM)}, ${q(trail.startPointName)}, ${n(trail.startLat)}, ${n(
          trail.startLng,
        )}, ${arr(trail.bestSeasons)}, ${q(trail.heroImage)}, ${arr(trail.gallery)}, ${json(trail.route)}, ${json(
          trail.itinerary,
        )}, ${arr(trail.facilities)}, ${q(trail.safetyNotes)}, ${q(trail.permitInfo)}, ${arr(
          trail.permitsRequired ?? [],
        )}, ${b(trail.isSample)}, ${b(trail.featured)}, ${b(trail.published)})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
);
lines.push('');

lines.push(
  'insert into public.guides (id, slug, full_name, region, languages, specialties, experience_years, day_rate_npr, bio, contact_email, contact_phone, verified, published, is_sample) values',
);
lines.push(
  sampleGuides
    .map(
      (guide) =>
        `  (${q(guide.id)}, ${q(guide.slug)}, ${q(guide.fullName)}, ${q(guide.region)}, ${arr(guide.languages)}, ${arr(
          guide.specialties,
        )}, ${n(guide.experienceYears)}, ${n(guide.dayRateNpr)}, ${q(guide.bio)}, ${q(guide.contactEmail)}, ${q(
          guide.contactPhone,
        )}, ${b(guide.verified)}, ${b(guide.published)}, ${b(guide.isSample)})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
);
lines.push('');

lines.push(
  'insert into public.stays (id, slug, name, type, region, destination_id, description, price_per_night_npr, amenities, photo_url, contact_email, lat, lng, published, is_sample) values',
);
lines.push(
  sampleStays
    .map(
      (stay) =>
        `  (${q(stay.id)}, ${q(stay.slug)}, ${q(stay.name)}, ${q(stay.type)}, ${q(stay.region)}, ${q(
          stay.destinationId,
        )}, ${q(stay.description)}, ${n(stay.pricePerNightNpr)}, ${arr(stay.amenities)}, ${q(stay.photoUrl)}, ${q(
          stay.contactEmail,
        )}, ${n(stay.lat)}, ${n(stay.lng)}, ${b(stay.published)}, ${b(stay.isSample)})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
);
lines.push('');
lines.push('-- No reviews are seeded: reviews must come from real signed-in users.');
lines.push('');
lines.push('-- Promote your own account after signing up:');
lines.push("-- update public.profiles set role = 'admin' where id = (select id from auth.users where email = 'you@example.com');");
lines.push('');
lines.push('commit;');

const outputPath = path.join(root, 'supabase/seed.sql');
await writeFile(outputPath, lines.join('\n') + '\n', 'utf8');
console.log(`Wrote ${outputPath}`);
console.log(
  `Seeded ${sampleDestinations.length} destinations, ${sampleTrails.length} trails, ${sampleGuides.length} guides, ${sampleStays.length} stays.`,
);
